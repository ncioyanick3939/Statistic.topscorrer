-- Topscorer AI 2.0 initial PostgreSQL schema proposal.
-- Not applied to Render. Review with a database backup before deployment.

CREATE TABLE IF NOT EXISTS seasons (
  season_end_year SMALLINT PRIMARY KEY,
  display_name TEXT NOT NULL,
  starts_on DATE NOT NULL,
  ends_on DATE NOT NULL,
  CHECK (ends_on > starts_on)
);

CREATE TABLE IF NOT EXISTS teams (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sihf_team_id BIGINT UNIQUE,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS players (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sihf_player_id BIGINT UNIQUE,
  full_name TEXT NOT NULL,
  normalized_name TEXT NOT NULL,
  primary_position TEXT NOT NULL CHECK (primary_position IN ('F', 'D', 'G')),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS data_import_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source TEXT NOT NULL,
  dataset TEXT NOT NULL,
  season_end_year SMALLINT REFERENCES seasons(season_end_year),
  status TEXT NOT NULL CHECK (status IN ('pending', 'running', 'succeeded', 'partial', 'failed')),
  source_file_name TEXT,
  source_checksum TEXT,
  source_updated_at TIMESTAMPTZ,
  rows_received INTEGER NOT NULL DEFAULT 0 CHECK (rows_received >= 0),
  started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  finished_at TIMESTAMPTZ,
  error_summary TEXT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS games (
  sihf_game_id BIGINT PRIMARY KEY,
  season_end_year SMALLINT NOT NULL REFERENCES seasons(season_end_year),
  phase_id BIGINT,
  starts_at TIMESTAMPTZ NOT NULL,
  home_team_id BIGINT NOT NULL REFERENCES teams(id),
  away_team_id BIGINT NOT NULL REFERENCES teams(id),
  status TEXT NOT NULL DEFAULT 'scheduled',
  home_score SMALLINT CHECK (home_score IS NULL OR home_score >= 0),
  away_score SMALLINT CHECK (away_score IS NULL OR away_score >= 0),
  source_updated_at TIMESTAMPTZ,
  import_run_id BIGINT REFERENCES data_import_runs(id),
  CHECK (home_team_id <> away_team_id)
);

CREATE INDEX IF NOT EXISTS games_season_date_idx
  ON games (season_end_year, starts_at);
CREATE INDEX IF NOT EXISTS games_home_team_date_idx
  ON games (home_team_id, starts_at);
CREATE INDEX IF NOT EXISTS games_away_team_date_idx
  ON games (away_team_id, starts_at);

CREATE TABLE IF NOT EXISTS player_game_stats (
  sihf_game_id BIGINT NOT NULL REFERENCES games(sihf_game_id) ON DELETE CASCADE,
  player_id BIGINT NOT NULL REFERENCES players(id),
  team_id BIGINT NOT NULL REFERENCES teams(id),
  position TEXT NOT NULL CHECK (position IN ('F', 'D')),
  goals SMALLINT NOT NULL DEFAULT 0 CHECK (goals >= 0),
  assists SMALLINT NOT NULL DEFAULT 0 CHECK (assists >= 0),
  plus_minus SMALLINT,
  penalty_minutes SMALLINT NOT NULL DEFAULT 0 CHECK (penalty_minutes >= 0),
  shots_on_goal SMALLINT CHECK (shots_on_goal IS NULL OR shots_on_goal >= 0),
  shots_missed SMALLINT CHECK (shots_missed IS NULL OR shots_missed >= 0),
  shots_blocked SMALLINT CHECK (shots_blocked IS NULL OR shots_blocked >= 0),
  faceoffs_won SMALLINT CHECK (faceoffs_won IS NULL OR faceoffs_won >= 0),
  faceoffs_lost SMALLINT CHECK (faceoffs_lost IS NULL OR faceoffs_lost >= 0),
  time_on_ice_seconds INTEGER CHECK (time_on_ice_seconds IS NULL OR time_on_ice_seconds >= 0),
  import_run_id BIGINT REFERENCES data_import_runs(id),
  PRIMARY KEY (sihf_game_id, player_id)
);

CREATE INDEX IF NOT EXISTS player_game_stats_player_idx
  ON player_game_stats (player_id, sihf_game_id);
CREATE INDEX IF NOT EXISTS player_game_stats_team_idx
  ON player_game_stats (team_id, sihf_game_id);

CREATE TABLE IF NOT EXISTS goalie_game_stats (
  sihf_game_id BIGINT NOT NULL REFERENCES games(sihf_game_id) ON DELETE CASCADE,
  player_id BIGINT NOT NULL REFERENCES players(id),
  team_id BIGINT NOT NULL REFERENCES teams(id),
  shots_against SMALLINT CHECK (shots_against IS NULL OR shots_against >= 0),
  saves SMALLINT CHECK (saves IS NULL OR saves >= 0),
  goals_against SMALLINT NOT NULL DEFAULT 0 CHECK (goals_against >= 0),
  saves_percentage NUMERIC(5,2) CHECK (saves_percentage IS NULL OR saves_percentage BETWEEN 0 AND 100),
  seconds_played INTEGER CHECK (seconds_played IS NULL OR seconds_played >= 0),
  import_run_id BIGINT REFERENCES data_import_runs(id),
  PRIMARY KEY (sihf_game_id, player_id)
);

CREATE INDEX IF NOT EXISTS goalie_game_stats_player_idx
  ON goalie_game_stats (player_id, sihf_game_id);

-- SIHF season tables are stored as timestamped snapshots, preserving source history.
CREATE TABLE IF NOT EXISTS player_season_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_end_year SMALLINT NOT NULL REFERENCES seasons(season_end_year),
  phase_id BIGINT,
  player_id BIGINT NOT NULL REFERENCES players(id),
  team_id BIGINT REFERENCES teams(id),
  games_played SMALLINT NOT NULL DEFAULT 0 CHECK (games_played >= 0),
  goals SMALLINT NOT NULL DEFAULT 0 CHECK (goals >= 0),
  assists SMALLINT NOT NULL DEFAULT 0 CHECK (assists >= 0),
  points SMALLINT NOT NULL DEFAULT 0 CHECK (points >= 0),
  plus_minus SMALLINT,
  penalty_minutes SMALLINT NOT NULL DEFAULT 0 CHECK (penalty_minutes >= 0),
  snapshot_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  import_run_id BIGINT NOT NULL REFERENCES data_import_runs(id),
  UNIQUE (season_end_year, phase_id, player_id, import_run_id)
);

CREATE TABLE IF NOT EXISTS goalie_season_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_end_year SMALLINT NOT NULL REFERENCES seasons(season_end_year),
  phase_id BIGINT,
  player_id BIGINT NOT NULL REFERENCES players(id),
  team_id BIGINT REFERENCES teams(id),
  games_played SMALLINT NOT NULL DEFAULT 0 CHECK (games_played >= 0),
  goals_against SMALLINT NOT NULL DEFAULT 0 CHECK (goals_against >= 0),
  shots_against INTEGER CHECK (shots_against IS NULL OR shots_against >= 0),
  saves INTEGER CHECK (saves IS NULL OR saves >= 0),
  saves_percentage NUMERIC(5,2) CHECK (saves_percentage IS NULL OR saves_percentage BETWEEN 0 AND 100),
  goals_against_average NUMERIC(5,2) CHECK (goals_against_average IS NULL OR goals_against_average >= 0),
  snapshot_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  import_run_id BIGINT NOT NULL REFERENCES data_import_runs(id),
  UNIQUE (season_end_year, phase_id, player_id, import_run_id)
);

CREATE TABLE IF NOT EXISTS fantasy_rosters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL DEFAULT 'Mein Team',
  balance BIGINT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS fantasy_roster_entries (
  roster_id BIGINT NOT NULL REFERENCES fantasy_rosters(id) ON DELETE CASCADE,
  player_id BIGINT NOT NULL REFERENCES players(id),
  fantasy_average NUMERIC(8,2),
  market_value BIGINT CHECK (market_value IS NULL OR market_value >= 0),
  market_trend TEXT CHECK (market_trend IS NULL OR market_trend IN ('up', 'flat', 'down')),
  is_starter BOOLEAN NOT NULL DEFAULT FALSE,
  is_import BOOLEAN NOT NULL DEFAULT FALSE,
  added_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (roster_id, player_id)
);

CREATE TABLE IF NOT EXISTS forecast_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id BIGINT NOT NULL REFERENCES players(id),
  season_end_year SMALLINT NOT NULL REFERENCES seasons(season_end_year),
  target_date DATE NOT NULL,
  model_version TEXT NOT NULL,
  expected_fantasy_points NUMERIC(10,3),
  lower_estimate NUMERIC(10,3),
  upper_estimate NUMERIC(10,3),
  generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (lower_estimate IS NULL OR upper_estimate IS NULL OR lower_estimate <= upper_estimate)
);

CREATE INDEX IF NOT EXISTS forecast_snapshots_lookup_idx
  ON forecast_snapshots (season_end_year, target_date, player_id, generated_at DESC);
